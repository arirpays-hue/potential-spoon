// הפונקציה הראשית שבוחרת באופן חכם ומגוון את העקיצה המתאימה ביותר!
// ============================================================================
const char* getRoastForDeath(enum ObsType obs, int finalScore, int charIdx, int biomeIdx) {
    // 1. אם השחקן נפסל ממש על ההתחלה (סיכוי גבוה לעקיצת פתיחה קורעת)
    if (finalScore < 45 && (rand() % 100) < 65) {
        return PICK_RND(ROASTS_EARLY);
    }

    // 2. אם השחקן הגיע לניקוד גבוה מאוד ונפסל (סיכוי לעקיצת שיא כואבת)
    if (finalScore >= 3000 && (rand() % 100) < 40) {
        return PICK_RND(ROASTS_HIGH_SCORE);
    }

    // 3. בדיקה אם יש עקיצה ייעודית לדמות שבה השחקן משתמש (סיכוי של 35%)
    if ((rand() % 100) < 35) {
        const char* charRoast = getCharacterRoast(charIdx);
        if (charRoast != NULL) {
            return charRoast;
        }
    }

    // 4. שילוב חכם בין עקיצה ספציפית לאויב שהרג אותך (70%) לבין עקיצה על הביומה (30%)
    if ((rand() % 100) < 30 && biomeIdx >= 0 && biomeIdx < NUM_BIOMES) {
        return BIOME_ROASTS[biomeIdx][rand() % 2];
    }

    return getObstacleRoast(obs);
}
 
