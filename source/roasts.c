#include "game.h"
#include <stdlib.h>

// מאגר ענק של עקיצות סרקסטיות קורעות בעברית שמחליף את ה-AI לכל סיבת מוות, דמות וניקוד!
const char* getRoastForDeath(enum ObsType obs, int finalScore, int charIdx, int biomeIdx) {
    // 1. אם השחקן נפסל ממש על ההתחלה (מתחת ל-50 נקודות)
    if (finalScore < 50) {
        static const char* earlyRoasts[] = {
            "אפילו כפתור ההפעלה הזיע יותר ממך בסיבוב הזה",
            "שיא עולם חדש בלמות לפני שהמוזיקה התחילה!",
            "ניסית לקפוץ או שסתם בדקת אם המכשול קשיח?",
            "העיניים היו פקוחות או ששיחקת על עיוור?",
            "זה היה מהיר יותר מהזמן שלקח לך לבחור דמות!",
            "אפילו צב בביומת הביצה היה עובר את המכשול הראשון"
        };
        return earlyRoasts[rand() % 6];
    }

    // 2. עקיצות ייחודיות לפי דמויות ספציפיות (סטיב, המבורגר, נינג'ה וכו')
    if (charIdx == 17 && (rand() % 2 == 0)) return "סטיב יקר, פה זה לא מיינקראפט, אי אפשר לחצוב במכשול!";
    if (charIdx == 16 && (rand() % 2 == 0)) return "בתור קריפר היית אמור לפוצץ את המכשול, לא להתפוצץ עליו!";
    if (charIdx == 67 && (rand() % 2 == 0)) return "ההמבורגר שלך הפך הרגע לקציצה שטוחה במיוחד על הרצפה!";
    if (charIdx == 68 && (rand() % 2 == 0)) return "הפיצה התקררה ונמעכה במשלוח, אין טיפ הפעם!";
    if (charIdx == 1  && (rand() % 2 == 0)) return "עשית סלטות של נינג׳ה באוויר אבל שכחת לנחות כמו שצריך!";

    // 3. עקיצות ממוקדות לפי האויב המדויק שהרג את השחקן!
    switch (obs) {
        case OBS_ROCK:
            return (rand() % 2) ? "הסלע עמד שם אלף שנה, ועדיין הופתעת לראות אותו!" : "ניסית לשחק אבן נייר ומספריים עם סלע ענק. הסלע ניצח!";
        case OBS_CACTUS:
            return (rand() % 2) ? "חיבוק חם לקקטוס במדבר? רעיון דוקר במיוחד!" : "דיקור סיני עושים במרפאה, לא בריצה לתוך קקטוס!";
        case OBS_SNAKE:
            return (rand() % 2) ? "הנחש אפילו לא היה צריך לזוז כדי להכשיל אותך!" : "דרכת על נחש בג׳ונגל, והוא החליט להחזיר ביס!";
        case OBS_LOLLIPOP:
            return (rand() % 2) ? "נפסלת מסוכרייה על מקל! רופא השיניים שלך גאה בך!" : "מתיקות קטלנית: הסוכרייה ליקקה אותך במקום הפוך!";
        case OBS_MAGMA:
            return (rand() % 2) ? "טיפ לחיים: כדורי לבה רותחים הם לא טרמפולינה!" : "יצאת קריספי במיוחד! בפעם הבאה דלג מעל המאגמה!";
        case OBS_PENGUIN:
            return (rand() % 2) ? "הפסדת לפינגווין שמנמן בקרחון! איזו השפלה קפואה!" : "הפינגווין רק רצה להחליק שלום, ואתה התרסקת עליו!";
        case OBS_SHELL:
            return (rand() % 2) ? "מעדת על צדפה באוקיינוס! אפילו בת הים צוחקת!" : "חיפשת פנינה בתוך הצדפה ומצאת מסך פסילה!";
        case OBS_BARRIER:
            return (rand() % 2) ? "מחסום הלייזר בסייבר חתך לך את רצף הניצחונות!" : "חומת האש של הסייבר חסמה אותך כמו וירוס חובבן!";
        case OBS_RED_SHROOM:
            return (rand() % 2) ? "זו לא פטרייה שמגדילה אותך כמו במריו, זו פטריית פסילה!" : "אכלת פטרייה רעילה והתחלת לראות כוכבים!";
        case OBS_CRYSTAL_SPIKE:
            return (rand() % 2) ? "קריסטל נוצץ ויפה, חבל שנכנסת בו בראש פתוח!" : "יהלומים הם לנצח, אבל הריצה שלך נגמרה הרגע!";
        case OBS_GEAR:
            return (rand() % 2) ? "נתקעת בגלגלי השיניים של ביומת הקיטור!" : "המכונה ממשיכה לעבוד, אבל אתה יצאת מכלל פעולה!";
        case OBS_GRAVE:
            return (rand() % 2) ? "נתקעת במצבה בבית הקברות... לפחות לא צריך לסחוב אותך רחוק!" : "המצבה כבר הייתה מוכנה מראש בדיוק בשבילך!";
        case OBS_GOLD_POT:
            return (rand() % 2) ? "רצת מהר מדי לסיר הזהב בקצה הקשת ושכחת לקפוץ!" : "החמדנות הרגה את הקופץ! סיר הזהב נשאר שלם!";
        case OBS_PIXEL_BLOCK:
            return (rand() % 2) ? "נפסלת מקוביית 8 ביט בביומת הרטרו! שנות השמונים התקשרו!" : "אפילו פיקסל בודד הצליח לעצור את הריצה שלך!";
        case OBS_SANDCASTLE:
            return (rand() % 2) ? "הרסת לילד את ארמון החול בחוף וגם נפסלת על הדרך!" : "להיתקע בארמון חול? זה שיא חדש של עדינות!";
        case OBS_PUMPKIN:
            return (rand() % 2) ? "הדלעת של הסתיו עשתה לך תעלול בלי שום ממתק!" : "הפכת לפאי דלעת מהיר במיוחד!";
        case OBS_BARREL:
            return (rand() % 2) ? "חבית רעל ירוקה! עכשיו בטוח תצמח לך עין שלישית!" : "שחייה בחומצה רדיואקטיבית לא מומלצת לקופצים!";
        case OBS_BRICK:
            return (rand() % 2) ? "כולם יודעים שלדרוך על קוביית לגו בצעצועים זה כאב סופני!" : "קוביית משחק קטנה הפילה גיבור גדול!";
        default:
            break;
    }

    // 4. עקיצות לאויבים מעופפים
    if (obs >= OBS_BIRD_START) {
        static const char* airRoasts[] = {
            "ניסית לתפוס טרמפ על ציפור באמצע קפיצה?",
            "השמיים שייכים למעופפים, אתה אמור לנחות על הקרקע!",
            "התנגשות אווירית! מגדל הפיקוח לא אישר לך להמריא ככה!",
            "אפילו הציפורים בביומה הזו לא מבינות לאן קפצת!"
        };
        return airRoasts[rand() % 4];
    }

    // 5. עקיצות כלליות לשחקנים שהגיעו רחוק
    static const char* generalRoasts[] = {
        "הגעת כל כך רחוק רק כדי למעוד ברגע הכי שטותי!",
        "האצבע התעייפה או שפשוט ויתרת לטובת כוח המשיכה?",
        "ריצה מרשימה, אבל המכשול האחרון לא התרשם בכלל!",
        "כמעט שברת את המשחק, ובסוף המכשול שבר אותך!"
    };
    return generalRoasts[rand() % 4];
}
